import { useMemo, useState } from 'react';
import { CalendarClock, CheckCircle2, Download, Eye, FolderOpen, History, Lock, Play, ShieldCheck, Timer, Trash2, UserCheck, UserRound, UserX } from 'lucide-react';
import { formatDate, timeAgo } from '@healthx/shared';
import { Avatar } from '@/components/brand/Brand';
import { BackendBadge, Badge, Button, Card, CardSkeleton, EmptyState, Field, Input, Modal, Notice, Pagination, ProgressBar, SearchInput, useToast, type BadgeTone } from '@/components/ui';
import { cn, paginate, useDemoLoading } from '@/lib/utils';
import { CONSENT_LABELS, PRIVACY_TYPES, type AdminUser, type PrivacyRequest, type PrivacyStatus, type PrivacyType } from '../adminData';
import { useAccess, useAdmin } from '../adminState';
import { AdminHeader, AdminHero, FilterSelect, HeroStat, RowActions, SecurityNote, SortHeader, StatusPill, TableShell, Th, Toolbar } from '../components';
import { daysUntil, formatDateTime, maskEmail, useSort } from '../helpers';

const STATUS: Record<PrivacyStatus, { label: string; tone: BadgeTone }> = {
  new: { label: 'New', tone: 'sky' },
  in_progress: { label: 'In progress', tone: 'peach' },
  completed: { label: 'Completed', tone: 'green' },
};
const TYPE_ICON: Record<PrivacyType, typeof Download> = { export: Download, deletion: Trash2, consent_withdrawal: UserX };
const TYPE_TONE: Record<PrivacyType, string> = { export: 'bg-sky-50 text-sky-700', deletion: 'bg-rose-50 text-rose-700', consent_withdrawal: 'bg-lavender-50 text-lavender-700' };
const CHANNEL: Record<PrivacyRequest['channel'], string> = { privacy_center: 'Privacy Center (app)', email: 'Email', support: 'Support ticket' };
const PAGE = 8;
const DAY = 86_400_000;

function DueChip({ r }: { r: PrivacyRequest }) {
  if (r.status === 'completed') return <span className="text-ink-500">{formatDate(r.dueDate, 'short')}</span>;
  const d = daysUntil(r.dueDate);
  if (d < 0) return <StatusPill tone="danger">Overdue {-d}d</StatusPill>;
  if (d <= 2) return <StatusPill tone="warning">Due in {d}d</StatusPill>;
  return <span className="whitespace-nowrap text-ink-600">{formatDate(r.dueDate, 'short')}</span>;
}

/** Request detail + processing (export, deletion with typed confirmation, consent withdrawal). Never shows health values. */
function RequestDetail({ request, user, onClose }: { request: PrivacyRequest; user?: AdminUser; onClose: () => void }) {
  const { state, dispatch, audit, apiMode } = useAdmin();
  const toast = useToast();
  const me = state.session!.name;
  const [progress, setProgress] = useState<number | null>(null);
  const [confirmText, setConfirmText] = useState('');
  const [confirmErr, setConfirmErr] = useState<string | null>(null);
  const t = PRIVACY_TYPES[request.type];
  const open = request.status !== 'completed';
  const TypeIcon = TYPE_ICON[request.type];
  const heading = 'mb-3 flex items-center gap-2 font-mono text-[10.5px] font-medium uppercase tracking-[0.14em] text-ink-500';

  const update = (patch: Partial<PrivacyRequest>, text: string) =>
    dispatch({ type: 'UPSERT_PRIVACY', request: { ...request, ...patch, log: [...request.log, { at: new Date().toISOString(), by: me, text }] } });

  const start = () => {
    void update({ status: 'in_progress', assignee: me }, 'Started processing.').then((ok) => ok && toast.success('Request assigned to you', request.id));
    audit('privacy.start', request.id, `${t.label} · ${request.userId}`);
  };

  const finish = () => {
    if (request.type === 'deletion') {
      if (confirmText !== 'DELETE') {
        setConfirmErr('Type DELETE to confirm permanent deletion.');
        return;
      }
      // With the API, completing the request is what erases the account (server-side).
      if (user && !apiMode) dispatch({ type: 'UPDATE_USER', id: user.id, patch: { status: 'deleted', name: 'Deleted user', email: `deleted-${user.id}@redacted`, devices: [] } });
    }
    // With the API, completing a withdrawal turns the consent off server-side.
    if (!apiMode && request.type === 'consent_withdrawal' && user && request.consent) {
      dispatch({ type: 'UPDATE_USER', id: user.id, patch: { consents: { ...user.consents, [request.consent]: false } } });
    }
    setConfirmErr(null);
    setProgress(0);
    let p = 0;
    const timer = window.setInterval(() => {
      p += 25;
      setProgress(p);
      if (p >= 100) {
        window.clearInterval(timer);
        setProgress(null);
        const consent = CONSENT_LABELS[request.consent ?? 'analytics'];
        const text = apiMode
          ? request.type === 'export'
            ? 'Marked complete. Export files aren’t generated by the server yet — the user can download their own data from Privacy in the app.'
            : request.type === 'deletion'
              ? 'Account deleted on the server: wellness data erased and all sessions ended.'
              : request.consent === 'integrations'
                ? `${consent} consent turned off on the server; connected health sources were disconnected.`
                : `${consent} consent turned off on the server; related processing stopped.`
          : request.type === 'export'
            ? 'Export generated; secure download link emailed to the user (expires in 7 days).'
            : request.type === 'deletion'
              ? 'Account and data deleted across database, storage, caches and analytics identifiers.'
              : `${consent} consent withdrawn; related processing stopped.`;
        void dispatch({
          type: 'UPSERT_PRIVACY',
          request: { ...request, status: 'completed', assignee: request.assignee ?? me, completedAt: new Date().toISOString(), log: [...request.log, { at: new Date().toISOString(), by: me, text }] },
        }).then((ok) => ok && toast.success('Request completed', `${request.id} · ${t.label}`));
        audit(`privacy.${request.type}_completed`, request.id, request.userId);
      }
    }, 260);
  };

  return (
    <Modal open onClose={onClose} title={`${request.id} · ${t.label}`} description={`Requested ${formatDateTime(request.requestedAt)} via ${CHANNEL[request.channel]}`} size="lg">
      <div className="space-y-4">
        <div className="flex flex-wrap items-center gap-3 rounded-2xl bg-wash p-4">
          <span className={cn('flex h-11 w-11 shrink-0 items-center justify-center rounded-full', TYPE_TONE[request.type])}>
            <TypeIcon className="h-5 w-5" />
          </span>
          <div className="flex min-w-0 flex-1 flex-wrap items-center gap-1.5">
            <StatusPill tone={STATUS[request.status].tone}>{STATUS[request.status].label}</StatusPill>
            <Badge tone="gray">{t.srs}</Badge>
            {request.consent && <Badge tone="lavender">{CONSENT_LABELS[request.consent]}</Badge>}
          </div>
          <span className="flex items-center gap-1.5 text-sm text-ink-600">
            Due <DueChip r={request} />
          </span>
        </div>

        <section className="rounded-2xl border border-ink-100 p-4">
          <h3 className={heading}>
            <UserRound className="h-3.5 w-3.5 text-green-700" /> Account
          </h3>
          <dl className="grid gap-x-6 text-sm sm:grid-cols-2">
            {[
              ['User ID', request.userId],
              ['Email', user ? maskEmail(user.email) : '—'],
              ['Account status', user?.status.replace('_', ' ') ?? 'unknown'],
              ['Assignee', request.assignee ?? 'Unassigned'],
            ].map(([k, v]) => (
              <div key={k} className="flex justify-between gap-3 border-b border-ink-100 py-2">
                <dt className="text-ink-500">{k}</dt>
                <dd className={cn('font-semibold text-ink-800', k === 'Account status' && 'capitalize')}>{v}</dd>
              </div>
            ))}
          </dl>
          <p className="mt-3 flex items-start gap-2 rounded-xl bg-green-50 px-3 py-2.5 text-xs leading-relaxed text-green-900">
            <ShieldCheck className="mt-0.5 h-3.5 w-3.5 shrink-0 text-green-700" />
            Health logs are never shown while processing requests. Exports are generated and sent to the user directly — staff never open the file.
          </p>
        </section>

        <section className="rounded-2xl border border-ink-100 p-4">
          <h3 className={heading}>
            <History className="h-3.5 w-3.5 text-green-700" /> Timeline
          </h3>
          <ol className="relative space-y-3 border-l-2 border-ink-100 pl-5">
            {request.log.map((l, i) => (
              <li key={i} className="relative">
                <span className="absolute -left-[27px] top-1 h-3 w-3 rounded-full border-2 border-white bg-green-500 ring-2 ring-green-100" />
                <p className="text-sm text-ink-800">{l.text}</p>
                <p className="text-xs text-ink-400">
                  {l.by === 'system' ? 'System' : l.by} · {formatDateTime(l.at)}
                </p>
              </li>
            ))}
          </ol>
        </section>

        {open && (
          <section className="space-y-3 rounded-2xl bg-ink-50/70 p-4">
            <h3 className={heading}>
              <Lock className="h-3.5 w-3.5 text-green-700" /> Process this request
            </h3>
            {request.type === 'deletion' && request.status === 'in_progress' && (
              <>
                <Notice tone="warning">Permanent and irreversible. Backups are purged per the retention policy (D-20). Store subscriptions must be cancelled by the user [ADD A-21].</Notice>
                <Field label='Type "DELETE" to confirm' htmlFor="pr-del" error={confirmErr}>
                  <Input id="pr-del" value={confirmText} onChange={(e) => setConfirmText(e.target.value)} autoComplete="off" invalid={!!confirmErr} />
                </Field>
              </>
            )}
            {progress !== null && <ProgressBar value={progress / 100} label="Processing progress" />}
            <div className="flex flex-wrap items-center gap-2">
              {request.status === 'new' && (
                <Button leftIcon={<Play className="h-4 w-4" />} onClick={start}>
                  Start processing
                </Button>
              )}
              {request.status === 'in_progress' && (
                <Button
                  variant={request.type === 'deletion' ? 'danger' : 'primary'}
                  loading={progress !== null}
                  leftIcon={request.type === 'export' ? <Download className="h-4 w-4" /> : request.type === 'deletion' ? <Trash2 className="h-4 w-4" /> : <UserCheck className="h-4 w-4" />}
                  onClick={finish}
                >
                  {request.type === 'export' ? 'Generate & send export' : request.type === 'deletion' ? 'Delete permanently' : 'Apply consent withdrawal'}
                </Button>
              )}
              <BackendBadge className="self-center" />
            </div>
          </section>
        )}
      </div>
    </Modal>
  );
}

/** Privacy requests (§42): export, deletion and consent withdrawal — mockup "Privacy Requests". */
export default function PrivacyRequests() {
  const { state, dispatch, audit } = useAdmin();
  const { session } = useAccess();
  const toast = useToast();
  const loading = useDemoLoading(400);
  const [q, setQ] = useState('');
  const [type, setType] = useState('all');
  const [status, setStatus] = useState('open');
  const [page, setPage] = useState(1);
  const [openId, setOpenId] = useState<string | null>(null);
  const usersById = useMemo(() => new Map(state.users.map((u) => [u.id, u])), [state.users]);

  const open = state.privacy.filter((r) => r.status !== 'completed');
  const dueWeek = open.filter((r) => daysUntil(r.dueDate) <= 7);
  const completed30 = state.privacy.filter((r) => r.completedAt && Date.now() - new Date(r.completedAt).getTime() <= 30 * DAY);
  const spans = completed30.map((r) => (new Date(r.completedAt!).getTime() - new Date(r.requestedAt).getTime()) / DAY);
  const avg = spans.length ? (spans.reduce((a, b) => a + b, 0) / spans.length).toFixed(1) : '—';
  const onTime = completed30.filter((r) => r.completedAt!.slice(0, 10) <= r.dueDate).length;
  const oldest = open.length ? Math.max(...open.map((r) => Math.floor((Date.now() - new Date(r.requestedAt).getTime()) / DAY))) : 0;

  const filtered = useMemo(() => {
    const t = q.trim().toLowerCase();
    return state.privacy.filter(
      (r) =>
        (!t || `${r.id} ${r.userId}`.toLowerCase().includes(t)) &&
        (type === 'all' || r.type === type) &&
        (status === 'all' || (status === 'open' ? r.status !== 'completed' : r.status === status)),
    );
  }, [state.privacy, q, type, status]);
  const { sorted, key, dir, toggle } = useSort(filtered, 'due', { id: (r) => r.id, requested: (r) => r.requestedAt, due: (r) => r.dueDate, status: (r) => r.status });
  const pg = paginate(sorted, page, PAGE);
  const current = state.privacy.find((r) => r.id === openId);
  const f = <T,>(fn: (v: T) => void) => (v: T) => {
    fn(v);
    setPage(1);
  };
  const filtersOn = !!q || type !== 'all' || status !== 'open';
  const clear = () => {
    setQ('');
    setType('all');
    setStatus('open');
    setPage(1);
  };

  const quickStart = (r: PrivacyRequest) => {
    void dispatch({ type: 'UPSERT_PRIVACY', request: { ...r, status: 'in_progress', assignee: session!.name, log: [...r.log, { at: new Date().toISOString(), by: session!.name, text: 'Started processing.' }] } }).then(
      (ok) => ok && toast.success('Request assigned to you', r.id),
    );
    audit('privacy.start', r.id, `${PRIVACY_TYPES[r.type].label} · ${r.userId}`);
  };

  return (
    <>
      <AdminHeader title="Privacy requests" subtitle="Data export, account deletion and consent withdrawal requests from users (§42). Health data is never shown here." badge={<Badge tone="sky">{open.length} open</Badge>} />

      <AdminHero
        eyebrow="Privacy Center · §42"
        title={open.length ? `${open.length} open · ${dueWeek.length} due this week` : 'Every request is complete'}
        aside={
          <div className="grid grid-cols-2 gap-3">
            <HeroStat label="Open requests" value={open.length} icon={<FolderOpen className="h-3.5 w-3.5" />} hint={open.length ? `Oldest: ${oldest} days` : 'Nothing open'} />
            <HeroStat label="Due this week" value={dueWeek.length} icon={<CalendarClock className="h-3.5 w-3.5" />} hint="Placeholder window (D-20)" />
            <HeroStat label="Completed (30 days)" value={completed30.length} icon={<CheckCircle2 className="h-3.5 w-3.5" />} hint={completed30.length ? `${onTime} of ${completed30.length} on time` : 'None yet'} />
            <HeroStat label="Avg completion" value={avg === '—' ? avg : `${avg} d`} icon={<Timer className="h-3.5 w-3.5" />} hint="Mostly automated (simulated)" />
          </div>
        }
      >
        <p className="mt-2 max-w-xl text-[15px] leading-relaxed text-green-50/80">Exports go straight to the user and deletions run across every store. Staff see account status only — never the data itself.</p>
        <div className="mt-5 flex flex-wrap gap-2">
          {(Object.keys(PRIVACY_TYPES) as PrivacyType[]).map((k) => {
            const I = TYPE_ICON[k];
            const on = type === k;
            return (
              <button
                key={k}
                type="button"
                aria-pressed={on}
                onClick={() => f(setType)(on ? 'all' : k)}
                className={cn('inline-flex h-9 items-center gap-2 rounded-full px-3.5 text-sm font-semibold transition', on ? 'bg-green-100 text-green-950' : 'glass-dark hover:bg-green-900/60')}
              >
                <I className="h-4 w-4" />
                {PRIVACY_TYPES[k].label}
                <span className={cn('num rounded-full px-1.5 text-xs', on ? 'bg-green-900/10' : 'bg-green-950/40')}>{open.filter((r) => r.type === k).length}</span>
              </button>
            );
          })}
        </div>
      </AdminHero>

      <Toolbar>
        <div className="flex flex-col gap-3 lg:flex-row lg:items-end">
          <SearchInput value={q} onChange={f(setQ)} placeholder="Search request or user ID…" className="lg:max-w-sm lg:flex-1" />
          <div className="grid flex-1 grid-cols-2 gap-3 lg:max-w-md">
            <FilterSelect label="Type" value={type} onChange={f(setType)} options={[{ value: 'all', label: 'All types' }, ...(Object.keys(PRIVACY_TYPES) as PrivacyType[]).map((t) => ({ value: t, label: PRIVACY_TYPES[t].label }))]} />
            <FilterSelect
              label="Status"
              value={status}
              onChange={f(setStatus)}
              options={[
                { value: 'open', label: 'Open (new + in progress)' },
                { value: 'new', label: 'New' },
                { value: 'in_progress', label: 'In progress' },
                { value: 'completed', label: 'Completed' },
                { value: 'all', label: 'All' },
              ]}
            />
          </div>
          {filtersOn && (
            <button type="button" onClick={clear} className="inline-flex h-11 items-center self-start rounded-full px-3 text-sm font-semibold text-green-700 hover:bg-green-50 lg:ml-auto lg:self-end">
              Reset filters
            </button>
          )}
        </div>
      </Toolbar>

      {loading ? (
        <CardSkeleton lines={6} />
      ) : filtered.length === 0 ? (
        <Card>
          <EmptyState
            icon={<ShieldCheck className="h-6 w-6" />}
            title="No requests match"
            body="Try another filter — or enjoy the quiet queue."
            action={
              filtersOn ? (
                <Button size="sm" variant="secondary" onClick={clear}>
                  Reset filters
                </Button>
              ) : undefined
            }
          />
        </Card>
      ) : (
        <Card className="overflow-hidden">
          <TableShell minWidth={920}>
            <thead>
              <tr>
                <SortHeader label="Request" k="id" active={key} dir={dir} onSort={toggle} />
                <Th>User</Th>
                <Th>Type</Th>
                <SortHeader label="Requested" k="requested" active={key} dir={dir} onSort={toggle} />
                <SortHeader label="Due" k="due" active={key} dir={dir} onSort={toggle} />
                <SortHeader label="Status" k="status" active={key} dir={dir} onSort={toggle} />
                <Th>Assignee</Th>
                <Th className="w-12">
                  <span className="sr-only">Actions</span>
                </Th>
              </tr>
            </thead>
            <tbody>
              {pg.items.map((r) => {
                const u = usersById.get(r.userId);
                const I = TYPE_ICON[r.type];
                return (
                  <tr key={r.id} className="cursor-pointer" onClick={() => setOpenId(r.id)}>
                    <td className="whitespace-nowrap px-4 py-3 font-mono text-[13px] font-medium text-green-800">{r.id}</td>
                    <td className="px-4 py-3">
                      <span className="block font-semibold text-ink-800">{r.userId}</span>
                      <span className="block text-xs text-ink-500">{u ? maskEmail(u.email) : '—'}</span>
                    </td>
                    <td className="px-4 py-3 text-ink-700">
                      <span className="inline-flex items-center gap-2 whitespace-nowrap">
                        <span className={cn('flex h-7 w-7 items-center justify-center rounded-full', TYPE_TONE[r.type])}>
                          <I className="h-3.5 w-3.5" />
                        </span>
                        {PRIVACY_TYPES[r.type].label}
                      </span>
                      {r.consent && <span className="ml-9 block text-xs text-ink-500">{CONSENT_LABELS[r.consent]}</span>}
                    </td>
                    <td className="whitespace-nowrap px-4 py-3 text-ink-600">{timeAgo(r.requestedAt)}</td>
                    <td className="px-4 py-3">
                      <DueChip r={r} />
                    </td>
                    <td className="px-4 py-3">
                      <StatusPill tone={STATUS[r.status].tone}>{STATUS[r.status].label}</StatusPill>
                    </td>
                    <td className="whitespace-nowrap px-4 py-3 text-ink-600">
                      {r.assignee ? (
                        <span className="inline-flex items-center gap-2">
                          <Avatar name={r.assignee} size={26} />
                          {r.assignee}
                        </span>
                      ) : (
                        <span className="text-ink-400">Unassigned</span>
                      )}
                    </td>
                    <td className="px-2 py-3">
                      <RowActions
                        label={r.id}
                        actions={[
                          { label: 'Open', icon: Eye, onSelect: () => setOpenId(r.id) },
                          r.status === 'new' && { label: 'Start processing', icon: Play, onSelect: () => quickStart(r) },
                          r.status === 'in_progress' && { label: 'Process…', icon: CheckCircle2, onSelect: () => setOpenId(r.id) },
                        ]}
                      />
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </TableShell>
          <div className="border-t border-ink-100 p-4">
            <Pagination page={pg.page} pages={pg.pages} onChange={setPage} total={pg.total} label="requests" />
          </div>
        </Card>
      )}

      <Notice tone="info" className="mt-5" title="Deadlines">
        Response windows follow the rules of each launch market — 7 days is a placeholder until legal confirms them (D-20). Every step is written to the audit log.
      </Notice>
      <SecurityNote className="mt-3" />

      {current && <RequestDetail key={`${current.id}-${current.status}`} request={current} user={usersById.get(current.userId)} onClose={() => setOpenId(null)} />}
    </>
  );
}
