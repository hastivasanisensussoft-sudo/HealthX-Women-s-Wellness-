/** Maps the shared catalogue's icon keys (lucide names) to lucide-react-native components. */
import { createElement } from 'react';
import {
  Activity,
  Apple,
  Baby,
  BatteryFull,
  BatteryLow,
  BatteryMedium,
  BookOpen,
  Brain,
  CalendarHeart,
  ChartColumn,
  CircleDot,
  CircleSlash,
  CloudRain,
  Droplet,
  Droplets,
  Dumbbell,
  Flame,
  Flower,
  Flower2,
  Footprints,
  GlassWater,
  Heart,
  HeartPulse,
  Leaf,
  Moon,
  Move,
  PersonStanding,
  Salad,
  Scale,
  Shuffle,
  Smile,
  Sparkle,
  Sparkles,
  Sprout,
  StretchHorizontal,
  Sun,
  SunMoon,
  Thermometer,
  Utensils,
  Waves,
  Wind,
  Zap,
  type LucideIcon,
} from 'lucide-react-native';

const MAP: Record<string, LucideIcon> = {
  activity: Activity,
  apple: Apple,
  baby: Baby,
  'battery-full': BatteryFull,
  'battery-low': BatteryLow,
  'battery-medium': BatteryMedium,
  'book-open': BookOpen,
  brain: Brain,
  'calendar-heart': CalendarHeart,
  'bar-chart-3': ChartColumn,
  'circle-dot': CircleDot,
  'circle-slash': CircleSlash,
  'cloud-rain': CloudRain,
  droplet: Droplet,
  droplets: Droplets,
  dumbbell: Dumbbell,
  flame: Flame,
  flower: Flower,
  'flower-2': Flower2,
  footprints: Footprints,
  'glass-water': GlassWater,
  heart: Heart,
  'heart-pulse': HeartPulse,
  leaf: Leaf,
  moon: Moon,
  move: Move,
  'person-standing': PersonStanding,
  salad: Salad,
  scale: Scale,
  shuffle: Shuffle,
  smile: Smile,
  sparkle: Sparkle,
  sparkles: Sparkles,
  sprout: Sprout,
  'stretch-horizontal': StretchHorizontal,
  sun: Sun,
  'sun-moon': SunMoon,
  thermometer: Thermometer,
  utensils: Utensils,
  waves: Waves,
  wind: Wind,
  zap: Zap,
};

export function iconFor(key: string): LucideIcon {
  return MAP[key] ?? Sparkles;
}

export function KeyIcon({ name, size = 20, color }: { name: string; size?: number; color: string }) {
  return createElement(iconFor(name), { size, color, strokeWidth: 2 });
}
